#!/usr/bin/env node
// Generates supabase/tests/apply_targets_cases.test.sql from the shared fixture, so the TypeScript contract
// (ApplyTargetsArgs) and the SQL RPC (public.apply_targets) are pinned to the same boundary cases.
// Plain Node, no TS imports. Usage:
//   node packages/shared/scripts/gen-pgtap-cases.mjs           write the file
//   node packages/shared/scripts/gen-pgtap-cases.mjs --check   exit 1 if the file on disk is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const fixturePath = resolve(here, '../src/__fixtures__/apply-targets-cases.json');
const outPath = resolve(here, '../../../supabase/tests/apply_targets_cases.test.sql');

const USER = '77777777-7777-7777-7777-777777777777';
const cases = JSON.parse(readFileSync(fixturePath, 'utf8'));

const str = (s) => `'${String(s).replaceAll("'", "''")}'`;
const num = (n) => {
  if (!Number.isFinite(n)) throw new Error(`non-finite number in fixture: ${n}`);
  return String(n);
};

const TYPES = {
  p_goal_option: 'public.goal_option',
  p_sex: 'public.biological_sex',
  p_activity_level: 'public.activity_level',
  p_units: 'public.unit_system',
};

function arg(key, value) {
  if (key in TYPES) return `${key} => ${str(value)}::${TYPES[key]}`;
  if (typeof value === 'boolean') return `${key} => ${value}`;
  if (typeof value === 'string') return `${key} => ${str(value)}`;
  if (typeof value === 'number') return `${key} => ${num(value)}`;
  throw new Error(`unsupported value for ${key}`);
}

function call(c) {
  const parts = Object.entries(c.args).map(([k, v]) => arg(k, v));
  // Age is stored in the fixture; the RPC takes a birth year (same UTC calendar-year rule).
  parts.splice(
    Object.keys(c.args).indexOf('p_height_cm'),
    0,
    `p_birth_year => (extract(year from now() at time zone 'UTC')::integer - ${num(c.age)})::smallint`,
  );
  return `select public.apply_targets(\n    ${parts.join(',\n    ')}\n  )`;
}

const lines = [];
lines.push(
  '-- GENERATED by packages/shared/scripts/gen-pgtap-cases.mjs from',
  '-- packages/shared/src/__fixtures__/apply-targets-cases.json. Do not edit; run `pnpm gen:pgtap`.',
  '-- Each fixture case runs through public.apply_targets() as one authenticated user.',
  'begin;',
  `select plan(${cases.length});`,
  '',
  `insert into auth.users (id, email) values ('${USER}', 'fixture@example.com');`,
  '',
);

for (const c of cases) {
  const consent = c.consentOnServer ? 'now()' : 'null';
  lines.push(
    `-- ${c.name.replaceAll('\n', ' ')}`,
    'reset role;',
    `update public.profiles set health_data_consent_at = ${consent}, onboarding_completed_at = null where user_id = '${USER}';`,
    `delete from public.daily_targets where user_id = '${USER}';`,
    'set local role authenticated;',
    `select set_config('request.jwt.claims', '{"sub":"${USER}","role":"authenticated"}', true);`,
  );
  const sql = call(c);
  if (c.expect === 'ok') {
    lines.push(`select lives_ok($q$\n  ${sql}\n$q$, ${str(c.name)});`);
  } else {
    lines.push(`select throws_ok($q$\n  ${sql}\n$q$, 'P0001', ${str(c.expect)}, ${str(c.name)});`);
  }
  lines.push('');
}

lines.push('select * from finish();', 'rollback;', '');
const output = lines.join('\n');

if (process.argv.includes('--check')) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : null;
  if (current !== output) {
    console.error(
      'supabase/tests/apply_targets_cases.test.sql is stale. Run `pnpm gen:pgtap` and commit the result.',
    );
    process.exit(1);
  }
  console.log(`apply_targets_cases.test.sql is up to date (${cases.length} cases).`);
} else {
  writeFileSync(outPath, output);
  console.log(`Wrote ${outPath} (${cases.length} cases).`);
}
